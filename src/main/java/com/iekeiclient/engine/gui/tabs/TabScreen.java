package com.iekeiclient.engine.gui.tabs;

import com.iekeiclient.engine.gui.GuiTheme;
import com.iekeiclient.engine.gui.WidgetScreen;
import com.iekeiclient.engine.gui.utils.Cell;
import com.iekeiclient.engine.gui.widgets.WWidget;

public abstract class TabScreen extends WidgetScreen {
    public final Tab tab;

    public TabScreen(GuiTheme theme, Tab tab) {
        super(theme, tab.name);

        this.tab = tab;
    }

    public <T extends WWidget> Cell<T> addDirect(T widget) {
        return super.add(widget);
    }
}
