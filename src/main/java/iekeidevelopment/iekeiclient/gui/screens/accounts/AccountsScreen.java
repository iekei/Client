package iekeidevelopment.iekeiclient.gui.screens.accounts;

import iekeidevelopment.iekeiclient.gui.GuiTheme;
import iekeidevelopment.iekeiclient.gui.WindowScreen;
import iekeidevelopment.iekeiclient.gui.widgets.WAccount;
import iekeidevelopment.iekeiclient.gui.widgets.containers.WContainer;
import iekeidevelopment.iekeiclient.gui.widgets.containers.WHorizontalList;
import iekeidevelopment.iekeiclient.gui.widgets.pressable.WButton;
import iekeidevelopment.iekeiclient.systems.accounts.Account;
import iekeidevelopment.iekeiclient.systems.accounts.AccountType;
import iekeidevelopment.iekeiclient.systems.accounts.Accounts;
import iekeidevelopment.iekeiclient.utils.misc.NbtUtils;
import iekeidevelopment.iekeiclient.utils.network.MeteorExecutor;
import org.jetbrains.annotations.Nullable;

import static iekeidevelopment.iekeiclient.IekeiClient.mc;

public class AccountsScreen extends WindowScreen {
    public AccountsScreen(GuiTheme theme) {
        super(theme, "Accounts");
    }

    @Override
    public void initWidgets() {
        // Accounts
        for (Account<?> account : Accounts.get()) {
            WAccount wAccount = add(theme.account(this, account)).expandX().widget();
            wAccount.refreshScreenAction = this::reload;
        }

        // Add account
        WHorizontalList l = add(theme.horizontalList()).expandX().widget();

        addButton(l, "Cracked", () -> mc.setScreen(new AddCrackedAccountScreen(theme, this)));
        addButton(l, "Altening", () -> mc.setScreen(new AddAlteningAccountScreen(theme, this)));
        addButton(l, "Session", () -> mc.setScreen(new AddSessionAccountScreen(theme, this)));
        addButton(l, "Microsoft", () -> mc.setScreen(new AddMicrosoftAccountScreen(theme, this)));
    }

    private void addButton(WContainer c, String text, Runnable action) {
        WButton button = c.add(theme.button(text)).expandX().widget();
        button.action = action;
    }

    public static void addAccount(@Nullable AddAccountScreen screen, AccountsScreen parent, Account<?> account) {
        if (screen != null) screen.locked = true;

        MeteorExecutor.execute(() -> {
            if (!account.fetchInfo()) {
                mc.execute(() -> {
                    if (screen != null) screen.locked = false;
                });
                return;
            }

            Accounts.get().add(account);

            if (account.login()) {
                if (account.getType() != AccountType.Cracked) account.getCache().loadHead(parent::reload);
                Accounts.get().save();
            }

            mc.execute(() -> {
                if (screen != null) {
                    screen.locked = false;
                    screen.close();
                }

                parent.reload();
            });
        });
    }

    @Override
    public boolean toClipboard() {
        return NbtUtils.toClipboard(Accounts.get());
    }

    @Override
    public boolean fromClipboard() {
        return NbtUtils.fromClipboard(Accounts.get());
    }
}
